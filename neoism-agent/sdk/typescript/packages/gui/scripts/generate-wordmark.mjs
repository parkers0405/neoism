#!/usr/bin/env node
// Extract the actual SVG depth layers and Rust animation constants; no font glyphs.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../../../../../', import.meta.url);
const read = p => readFileSync(new URL(p, root), 'utf8');
const native = read('neoism-frontend/desktop/assets/splash/neoism-wordmark.svg');
const web = read('neoism-frontend/web/public/assets/neoism-wordmark.svg');
const extract = svg => [...svg.matchAll(/<g[^>]*fill="#ffffff" fill-opacity="([^"]+)"><g transform="([^"]+)"><g><path d="([^"]+)"/g)].map(m => ({ opacity: Number(m[1]), transform: m[2], d: m[3] }));
const layers = extract(native);
assert.equal(layers.length, 18);
assert.deepEqual(layers, extract(web), 'Desktop/web glyph geometry must agree');
const constants = read('neoism-frontend/shared/src/panels/agent_pane/view/mod.rs');
const names = ['LETTER_COUNT', 'LETTER_HOVER_RATE', 'LETTER_HOVER_SCALE', 'LETTER_HOVER_LIFT', 'LETTER_SHIMMER_AMP', 'LETTER_SHIMMER_PERIOD'];
const motion = Object.fromEntries(names.map(name => {
    const match = constants.match(new RegExp(`${name}: (?:f32|usize) = ([\\d.]+)`));
    assert(match, name);
    return [name, Number(match[1])];
}));
const letters = Array.from({ length: 6 }, (_, i) => [layers[i], layers[i + 6], layers[i + 12]]);
// Native PNG is the tightly cropped 0.8x raster (1196 x 193), not the web's padded 330-high viewBox.
const content = '// @generated by scripts/generate-wordmark.mjs; do not edit.\n' +
    `export const wordmarkLetters = ${JSON.stringify(letters, null, 2)} as const;\n` +
    `export const wordmarkMotion = ${JSON.stringify(motion, null, 2)} as const;\n` +
    'export const wordmarkGeometry = { width: 1495, height: 241.25, top: 602.5 } as const;\n';
const output = new URL('../src/generated/wordmark.ts', import.meta.url);
if (process.argv.includes('--check')) assert.equal(readFileSync(output, 'utf8'), content, 'Run node scripts/generate-wordmark.mjs');
else writeFileSync(output, content);
