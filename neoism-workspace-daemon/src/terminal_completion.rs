//! Host-owned completion. Prompt hooks publish trusted shell metadata privately;
//! requests are DATA (argv), never shell programs and never PTY writes.
use neoism_protocol::pty::TerminalCompletion;
use std::{collections::HashSet, path::{Path, PathBuf}, time::Duration};
use tokio::{io::AsyncReadExt, process::Command, sync::Semaphore};

const MAX_LINE: usize = 8192;
const MAX_STATE: u64 = 2 * 1024 * 1024;
const MAX_OUTPUT: u64 = 256 * 1024;
static WORKERS: Semaphore = Semaphore::const_new(4);

pub(super) struct Snapshot { dir: PathBuf, shell: String, bash: bool }
impl Snapshot {
    pub(super) fn new(shell: &str) -> Result<Self, String> {
        #[cfg(not(unix))]
        return Err("Safe host completion is not integrated on this platform".into());
        #[cfg(unix)]
        {
            use std::os::unix::fs::DirBuilderExt;
            let dir = std::env::temp_dir().join(format!("neoism-completion-{}", uuid::Uuid::new_v4()));
            std::fs::DirBuilder::new().mode(0o700).create(&dir).map_err(|e| e.to_string())?;
            Ok(Self { dir, shell: shell.into(), bash: Path::new(shell).file_name().is_some_and(|n| n == "bash") })
        }
    }
    pub(super) fn directory(&self) -> &Path { &self.dir }
}
impl Drop for Snapshot { fn drop(&mut self) { let _ = std::fs::remove_dir_all(&self.dir); } }

// No query is delivered to either hook. Atomic rename publishes one generation
// containing cwd, exported environment, aliases, functions and completion specs.
// A subshell contains umask/options/traps and cannot change the interactive shell.
pub(super) const BASH_HOOK: &str = r#"
__neoism_completion_snapshot() (
  trap - DEBUG
  [ -n "${NEOISM_COMPLETION_DIR:-}" ] || return 0
  umask 077
  ulimit -f 4096
  __neoism_cwd=$(builtin pwd -P) || return 0
  /bin/rm -f -- "$NEOISM_COMPLETION_DIR/meta" || return 0
  {
    builtin printf '# neoism-bash-snapshot\n'
    builtin printf 'builtin cd -- %q\n' "$__neoism_cwd"
    builtin export -p
    # User completers also depend on ordinary non-exported scalars and arrays,
    # not just bash-completion's _comp* globals. Serialize declarations as DATA
    # generated by Bash, in one bounded private file. Do not restore volatile
    # interpreter state or namerefs into the worker. Readonly values are copied
    # without their readonly attribute so worker bookkeeping remains writable.
    while IFS= read -r __neoism_decl; do
      __neoism_attrs=${__neoism_decl#declare }; __neoism_attrs=${__neoism_attrs%% *}
      [[ $__neoism_attrs == *n* || $__neoism_attrs == *x* ]] && continue
      __neoism_name=${__neoism_decl#declare * }; __neoism_name=${__neoism_name%%=*}
      case "$__neoism_name" in
        COMP_WORDBREAKS|BASH_COMPLETION*) ;;
        __neoism*|BASH*|COMP_*|EUID|UID|PPID|SHELLOPTS|DIRSTACK|GROUPS|PIPESTATUS|FUNCNAME|LINENO|IFS|OPTIND|OPTARG|RANDOM|SRANDOM|SECONDS|EPOCH*|HIST*|PROMPT_COMMAND|PS[0-9]|PWD|OLDPWD|SHLVL|_) continue ;;
      esac
      __neoism_attrs=${__neoism_attrs//r/}; [[ $__neoism_attrs == '-' ]] && __neoism_attrs='--'
      builtin printf 'declare %s %s\n' "$__neoism_attrs" "${__neoism_decl#declare * }"
    done < <(builtin declare -p)
    builtin alias -p
    builtin declare -f
    builtin complete -p
    builtin printf '__neoism_live_variables=('; builtin printf ' %q' $(builtin compgen -v); builtin printf ' )\n'
  } > "$NEOISM_COMPLETION_DIR/state.tmp" 2>/dev/null || return 0
  /bin/mv -f -- "$NEOISM_COMPLETION_DIR/state.tmp" "$NEOISM_COMPLETION_DIR/state" 2>/dev/null || return 0
  builtin printf '%s\0%s\0%s\0' "$__neoism_cwd" "$PATH" "$HOME" > "$NEOISM_COMPLETION_DIR/meta.tmp" || return 0
  /bin/mv -f -- "$NEOISM_COMPLETION_DIR/meta.tmp" "$NEOISM_COMPLETION_DIR/meta" 2>/dev/null
)
"#;

// zsh's ZLE completion widgets require an interactive editor context. Do not
// pretend that invoking them from `zsh -c` is equivalent. Publish live names and
// environment for the explicitly labeled host fallback instead.
pub(super) const ZSH_HOOK: &str = r#"
__neoism_completion_snapshot() (
  [[ -n ${NEOISM_COMPLETION_DIR:-} ]] || return 0
  umask 077
  ulimit -f 4096
  __neoism_cwd=$(builtin pwd -P) || return 0
  /bin/rm -f -- "$NEOISM_COMPLETION_DIR/meta" || return 0
  builtin printf '%s\0%s\0%s\0' "$__neoism_cwd" "$PATH" "$HOME" > "$NEOISM_COMPLETION_DIR/meta.tmp"
  { builtin printf '%s\n' ${(k)aliases}; } > "$NEOISM_COMPLETION_DIR/aliases"
  { builtin printf '%s\n' ${(k)functions}; } > "$NEOISM_COMPLETION_DIR/functions"
  { builtin printf '%s\n' ${(k)parameters}; } > "$NEOISM_COMPLETION_DIR/variables"
  /bin/mv -f -- "$NEOISM_COMPLETION_DIR/meta.tmp" "$NEOISM_COMPLETION_DIR/meta" 2>/dev/null
)
"#;

pub(super) fn validate(line: &str, cursor: u32) -> Result<(), String> {
    if line.len() > MAX_LINE || cursor as usize > line.len() || !line.is_char_boundary(cursor as usize)
        || line.chars().any(char::is_control) {
        return Err("Invalid completion line/cursor (UTF-8 byte offset, single line, 8192-byte maximum)".into());
    }
    // Intentionally bounded to a simple command. Never pass expansions or shell
    // programs to third-party completers, some of which eval COMP_LINE themselves.
    let mut quote = None;
    let mut escaped = false;
    for (i, c) in line.char_indices() {
        if escaped { escaped = false; continue; }
        if c == '\\' && quote != Some('\'') { escaped = true; continue; }
        if quote == Some(c) { quote = None; continue; }
        if quote.is_none() && (c == '\'' || c == '"') { quote = Some(c); continue; }
        if (quote.is_none() && ";|&<>".contains(c))
            || (quote != Some('\'') && (c == '`' || line[i..].starts_with("$(") || line[i..].starts_with("${"))) {
            return Err("Completion of shell operators/substitutions is not supported".into());
        }
    }
    Ok(())
}

#[derive(Debug)]
struct Input { words: Vec<String>, index: usize, start: usize, end: usize, prefix: String }
fn input(line: &str, cursor: usize) -> Input {
    let mut spans = Vec::new();
    let mut start = None;
    let mut quote = None;
    let mut escaped = false;
    for (i, c) in line.char_indices() {
        if start.is_none() && !c.is_whitespace() { start = Some(i); }
        if escaped { escaped = false; continue; }
        if c == '\\' && quote != Some('\'') { escaped = true; continue; }
        if quote == Some(c) { quote = None; }
        else if quote.is_none() && (c == '\'' || c == '"') { quote = Some(c); }
        else if quote.is_none() && c.is_whitespace() {
            if let Some(s) = start.take() { spans.push((s, i)); }
        }
    }
    if let Some(s) = start { spans.push((s, line.len())); }
    let active = spans.iter().position(|&(s,e)| s <= cursor && cursor <= e);
    let index = active.unwrap_or_else(|| spans.iter().filter(|&&(_,e)| e < cursor).count());
    let (start,end) = active.map(|i| spans[i]).unwrap_or((cursor,cursor));
    let mut words: Vec<_> = spans.iter().map(|&(s,e)| unquote(&line[s..e])).collect();
    let prefix = unquote(&line[start..cursor]);
    if active.is_none() { words.insert(index, String::new()); }
    words[index] = prefix.clone();
    Input { words, index, start, end, prefix }
}
fn unquote(s: &str) -> String {
    let mut out = String::new(); let mut quote = None;
    let mut chars = s.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\\' && quote != Some('\'') {
            // Inside double quotes a backslash before ordinary filename
            // characters is literal, not a generic shell escape.
            if quote == Some('"') && chars.peek().is_some_and(|next| !matches!(*next, '$'|'`'|'"'|'\\')) {
                out.push('\\');
            } else if let Some(next) = chars.next() { out.push(next); }
        }
        else if quote == Some(c) { quote = None; }
        else if quote.is_none() && (c == '\'' || c == '"') { quote = Some(c); }
        else { out.push(c); }
    }
    out
}
fn quote(s: &str) -> String {
    if !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || "_/-.,:=+@%".contains(c)) { s.into() }
    else { format!("'{}'", s.replace('\'', "'\\''")) }
}

fn completion_line(line: &str, parsed: &Input, cursor: u32, kind: &str, value: &str) -> String {
    let replacement = if kind == "variable" { format!("${value}") }
        else if matches!(kind, "file"|"directory") && value.starts_with('-') { quote(&format!("./{value}")) }
        else { quote(value) };
    // The delimiter is shell syntax, outside any quoting. Never alter a suffix
    // or insert a space into a directory/variable/--option= continuation.
    let delimiter = if cursor as usize == line.len() && parsed.end == line.len()
        && !matches!(kind, "directory"|"variable")
        && !(kind == "option" && value.ends_with('=')) { " " } else { "" };
    format!("{}{}{}{}", &line[..parsed.start], replacement, delimiter, &line[parsed.end..])
}

// Group ownership survives futures being cancelled on disconnect: kill the
// entire worker tree, not just Bash (completion functions may spawn children).
struct ProcessGroup(u32);
impl Drop for ProcessGroup {
    fn drop(&mut self) {
        #[cfg(unix)]
        unsafe { libc::kill(-(self.0 as i32), libc::SIGKILL); }
    }
}

async fn bounded_read(path: &Path, limit: u64) -> Result<Vec<u8>, String> {
    let mut bytes = Vec::new();
    tokio::fs::File::open(path).await.map_err(|e| e.to_string())?.take(limit + 1)
        .read_to_end(&mut bytes).await.map_err(|e| e.to_string())?;
    if bytes.len() as u64 > limit { return Err("Host completion metadata exceeds limit".into()); }
    Ok(bytes)
}

pub(super) async fn complete(snapshot: &Snapshot, line: &str, cursor: u32) -> Result<(Vec<TerminalCompletion>, String), String> {
    validate(line, cursor)?;
    let _permit = WORKERS.try_acquire().map_err(|_| "Host completion workers are busy")?;
    let parsed = input(line, cursor as usize);
    let metadata = bounded_read(&snapshot.dir.join("meta"), 65536).await
        .map_err(|_| "Host shell has not published a valid prompt snapshot")?;
    let fields: Vec<_> = metadata.split(|b| *b == 0).collect();
    if fields.len() < 4 { return Err("Incomplete host shell metadata".into()); }
    let cwd = std::str::from_utf8(fields[0]).map_err(|_| "Host cwd is not UTF-8")?;
    let path = std::str::from_utf8(fields[1]).map_err(|_| "Host PATH is not UTF-8")?;
    let home = std::str::from_utf8(fields[2]).map_err(|_| "Host home is not UTF-8")?;
    if snapshot.bash {
        let state = tokio::fs::metadata(snapshot.dir.join("state")).await.map_err(|_| "Missing Bash snapshot")?;
        if state.len() > MAX_STATE { return Err("Bash completion snapshot exceeds 2 MiB limit".into()); }
    }
    let mut command = Command::new(if snapshot.bash { &snapshot.shell } else { "/bin/bash" });
    command.env_clear().env("PATH", path).env("HOME", home)
        .current_dir(cwd).args(["--noprofile", "--norc", "-c", WORKER, "neoism-completion"])
        .arg(if snapshot.bash { snapshot.dir.join("state") } else { PathBuf::new() })
        .arg(line).arg(cursor.to_string()).arg(parsed.index.to_string()).args(&parsed.words)
        .stdin(std::process::Stdio::null()).stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::null()).kill_on_drop(true);
    #[cfg(unix)]
    unsafe {
        // A private session/group also prevents native completers opening
        // /dev/tty from reaching the daemon's inherited controlling terminal.
        command.pre_exec(|| {
            if libc::setsid() < 0 { Err(std::io::Error::last_os_error()) } else { Ok(()) }
        });
    }
    let mut child = command.spawn().map_err(|e| format!("Cannot start host completion worker: {e}"))?;
    let group = ProcessGroup(child.id().ok_or("Completion worker exited")?);
    let mut stdout = child.stdout.take().ok_or("Missing completion pipe")?.take(MAX_OUTPUT + 1);
    let mut output = Vec::new();
    let run = async {
        stdout.read_to_end(&mut output).await.map_err(|e| e.to_string())?;
        if output.len() as u64 > MAX_OUTPUT { return Err("Completion output exceeded limit".into()); }
        let status = child.wait().await.map_err(|e| e.to_string())?;
        if !status.success() { return Err("Host completion worker failed".into()); }
        Ok(())
    };
    let result = tokio::time::timeout(Duration::from_millis(1200), run).await;
    drop(group);
    if !matches!(result, Ok(Ok(()))) {
        let _ = child.kill().await;
        let _ = child.wait().await;
        return Err(match result { Ok(Err(e)) => e, _ => "Host completion timed out".into() });
    }
    let mut candidates = Vec::new();
    let parts: Vec<_> = output.split(|b| *b == 0).collect();
    for record in parts.chunks_exact(3) {
        if let (Ok(kind), Ok(value), Ok(detail)) = (std::str::from_utf8(record[0]), std::str::from_utf8(record[1]), std::str::from_utf8(record[2])) {
            candidates.push((kind.to_string(), value.to_string(), detail.to_string()));
        }
    }
    if !snapshot.bash && parsed.index == 0 {
        for (file,kind) in [("aliases","alias"),("functions","function")] {
            if let Ok(names) = bounded_read(&snapshot.dir.join(file), 131072).await.and_then(|b| String::from_utf8(b).map_err(|e|e.to_string())) {
                for name in names.lines().filter(|n| n.starts_with(&parsed.prefix)).take(200) {
                    candidates.push((kind.into(), name.into(), "Live zsh name".into()));
                }
            }
        }
    }
    if !snapshot.bash && parsed.prefix.starts_with('$') {
        if let Ok(names) = bounded_read(&snapshot.dir.join("variables"), 131072).await.and_then(|b| String::from_utf8(b).map_err(|e|e.to_string())) {
            for name in names.lines().filter(|n| n.starts_with(&parsed.prefix[1..])).take(200) {
                candidates.push(("variable".into(), name.into(), "Live zsh variable name".into()));
            }
        }
    }
    if parsed.index >= 2 && matches!(parsed.words.first().map(String::as_str), Some("npm"|"pnpm"|"yarn"|"bun"))
        && matches!(parsed.words.get(1).map(String::as_str), Some("run"|"run-script")) {
        let package = Path::new(cwd).join("package.json");
        if tokio::fs::metadata(&package).await.is_ok_and(|m| m.len() <= 262144) {
            if let Ok(bytes) = bounded_read(&package, 262144).await {
                if let Ok(json) = serde_json::from_slice::<serde_json::Value>(&bytes) {
                    if let Some(scripts) = json.get("scripts").and_then(|v| v.as_object()) {
                        for (name, value) in scripts.iter().filter(|(name,_)| name.starts_with(&parsed.prefix)).take(200) {
                            candidates.push(("script".into(), name.clone(), value.as_str().unwrap_or("").chars().take(200).collect()));
                        }
                    }
                }
            }
        }
    }
    let mut seen = HashSet::new();
    let mut entries = Vec::new();
    // Prefer domain-aware labels over an installed completer's generic argument
    // when both provide the same candidate.
    candidates.sort_by_key(|(kind,_,detail)| match kind.as_str() {
        "alias"|"function"|"variable"|"branch"|"remote"|"script" => 0,
        "option"|"command" => 1,
        "directory"|"file" if detail == "Host filesystem" => 4,
        "argument"|"directory"|"file" => 2, _ => 3,
    });
    for (kind, value, detail) in candidates {
        if entries.len() >= 200 { break; }
        if value.is_empty() || value.len() > 4096 || value.chars().any(char::is_control) || !seen.insert(value.clone()) { continue; }
        if kind == "variable" && !value.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') { continue; }
        entries.push(TerminalCompletion { value: completion_line(line, &parsed, cursor, &kind, &value), label: if kind == "variable" { format!("${value}") } else { value }, detail: detail.chars().filter(|c| !c.is_control()).take(200).collect(), kind });
    }
    Ok((entries, if snapshot.bash { "bash-live-snapshot+native+host" } else { "zsh-live-metadata+host-fallback (no ZLE completers)" }.into()))
}

const WORKER: &str = include_str!("terminal_completion.bash");

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn validation_and_spans() {
        assert!(validate("é", 1).is_err());
        assert!(validate("echo $(touch /tmp/no)", 24).is_err());
        assert!(validate("a\n", 2).is_err());
        let p = input("cat 'two wo' --flag", 11);
        assert_eq!(p.prefix, "two wo");
        assert_eq!(&"cat 'two wo' --flag"[p.end..], " --flag");
        assert_eq!(quote("a'b $x"), "'a'\\''b $x'");
        assert_eq!(unquote(r#""a\b""#), r"a\b");
        assert_eq!(unquote(r"two\ words"), "two words");
    }

    #[test]
    fn completion_delimiters_are_outside_quotes_and_preserve_suffix() {
        for kind in ["command", "alias", "function", "branch", "remote", "script", "file", "option", "argument"] {
            let line = "cmd par";
            assert_eq!(completion_line(line, &input(line, line.len()), line.len() as u32, kind, "two words'"), "cmd 'two words'\\''' ");
        }
        assert_eq!(completion_line("gi", &input("gi", 2), 2, "command", "git"), "git ");
        assert_eq!(completion_line("cd tw", &input("cd tw", 5), 5, "directory", "two words/"), "cd 'two words/'");
        assert_eq!(completion_line("echo $PA", &input("echo $PA", 8), 8, "variable", "PATH"), "echo $PATH");
        assert_eq!(completion_line("tool --ou", &input("tool --ou", 9), 9, "option", "--output="), "tool --output=");
        let line = "cmd par --keep";
        assert_eq!(completion_line(line, &input(line, 7), 7, "file", "two words"), "cmd 'two words' --keep");
    }
}