// Idle time is mostly breathing, with a rotating fidget (wave, stretch,
// scratch, look around) every other 2-second window so he never loops
// the same two frames for long.
fn idle_fidget_frame(tick: i32) -> &'static [&'static str] {
    match (tick / 16) % 8 {
        1 => {
            if tick & 1 == 0 {
                PET_WAVE_A
            } else {
                PET_WAVE_B
            }
        }
        3 => match (tick / 4) % 4 {
            0 | 3 => PET_STRETCH_A,
            _ => PET_STRETCH_B,
        },
        5 => {
            if tick & 1 == 0 {
                PET_ITCH_A
            } else {
                PET_ITCH_B
            }
        }
        7 => {
            if (tick / 4) & 1 == 0 {
                PET_OBSERVE_A
            } else {
                PET_OBSERVE_B
            }
        }
        _ => {
            if (tick / 4) & 1 == 0 {
                PET_IDLE_A
            } else {
                PET_IDLE_B
            }
        }
    }
}

#[rustfmt::skip]
fn draw_stick_pet(
    sugarloaf: &mut Sugarloaf,
    display: [f32; 4],
    scale: f32,
    pet: &PetState,
    animation_seconds: f32,
    impact_seconds: f32,
    turn_seconds: f32,
    ink: [f32; 4],
    anger: [f32; 4],
) {
    let mut x = pet.position.x.round();
    let mut y = pet.position.y.round();
    let tick = (animation_seconds * 8.0) as i32;
    let style = pet.style();
    let moment = pet.moment();
    let airborne = !pet.grabbed && pet.position.y < WORLD_FLOOR - 0.5;
    let walking_style = matches!(
        style,
        CritterStyle::Stroll | CritterStyle::March | CritterStyle::Skip
            | CritterStyle::Sneak | CritterStyle::Moonwalk | CritterStyle::Zoomies
    );
    let resting = style == CritterStyle::Sleep && !pet.grabbed && !airborne;
    if resting {
        y -= 7.0; // lie on the bed platform
    }
    let facing = if pet.facing_right { 1.0 } else { -1.0 };
    let mut draw_facing = pet.facing_right;

    let frame: &[&str] = if pet.grabbed {
        if tick & 1 == 0 { PET_GRAB_A } else { PET_GRAB_B }
    } else if airborne {
        if tick & 1 == 0 { PET_FALL_A } else { PET_FALL_B }
    } else if impact_seconds > 0.0 {
        PET_LAND
    } else if let Some(moment) = moment {
        match moment {
            Moment::Sneeze => if pet.moment_phase() < 0.45 { PET_SNEEZE_A } else { PET_SNEEZE_B },
            Moment::Shiver => { x += if tick & 1 == 0 { 1.0 } else { -1.0 }; PET_IDLE_A }
            Moment::Hiccup => { if tick & 1 == 0 { y -= 1.0; } PET_IDLE_A }
            Moment::Stare => PET_STARE,
            Moment::Trip => if pet.moment_phase() < 0.4 { PET_TRIP } else { PET_FLAT },
            Moment::Dizzy => if tick & 1 == 0 { PET_DIZZY_A } else { PET_DIZZY_B },
        }
    } else if turn_seconds > 0.0 && walking_style {
        PET_IDLE_A // brief front-facing frame sells the direction change
    } else {
        match style {
            CritterStyle::Fidget => idle_fidget_frame(tick),
            CritterStyle::Stroll =>
                [PET_WALK_A, PET_WALK_B, PET_WALK_C, PET_WALK_D][(tick % 4) as usize],
            CritterStyle::March => if tick & 1 == 0 { PET_MARCH_A } else { PET_MARCH_B },
            CritterStyle::Skip => if tick & 1 == 0 { PET_SKIP_A } else { PET_SKIP_B },
            CritterStyle::Sneak => if (tick / 2) & 1 == 0 { PET_SNEAK_A } else { PET_SNEAK_B },
            CritterStyle::Moonwalk => {
                draw_facing = !draw_facing; // glide backwards, face forwards
                if tick & 1 == 0 { PET_MOON_A } else { PET_MOON_B }
            }
            CritterStyle::Zoomies => if tick & 1 == 0 { PET_RUN_A } else { PET_RUN_B },
            CritterStyle::Dance =>
                [PET_PLAY_A, PET_PLAY_C, PET_PLAY_B, PET_PLAY_D][(tick % 4) as usize],
            CritterStyle::Robot => if (tick / 2) & 1 == 0 { PET_ROBOT_A } else { PET_ROBOT_B },
            CritterStyle::AirGuitar => if tick & 1 == 0 { PET_GUITAR_A } else { PET_GUITAR_B },
            CritterStyle::Juggle => if tick & 1 == 0 { PET_JUGGLE_A } else { PET_JUGGLE_B },
            CritterStyle::Spin => {
                draw_facing = (tick % 4) < 2;
                if tick & 1 == 0 { PET_PLAY_B } else { PET_SPIN_SIDE }
            }
            CritterStyle::Boxing => match tick % 4 {
                0 => PET_PUNCH_GUARD,
                1 => PET_PUNCH_WINDUP,
                _ => PET_PUNCH_JAB,
            },
            CritterStyle::Pushups => if (tick / 2) & 1 == 0 { PET_PUSHUP_A } else { PET_PUSHUP_B },
            CritterStyle::Squats => if (tick / 2) & 1 == 0 { PET_SQUAT } else { PET_IDLE_A },
            CritterStyle::JumpRope => if tick & 1 == 0 { PET_ROPE_A } else { PET_ROPE_B },
            CritterStyle::Sleep => if (tick / 8) & 1 == 0 { PET_SLEEP_A } else { PET_SLEEP_B },
            CritterStyle::Hammer => if tick & 1 == 0 { PET_WORK_A } else { PET_WORK_B },
            CritterStyle::Read => if (tick / 6) & 1 == 0 { PET_READ_A } else { PET_READ_B },
            CritterStyle::Gaze | CritterStyle::BirdWatch =>
                if (tick / 4) & 1 == 0 { PET_OBSERVE_A } else { PET_OBSERVE_B },
            CritterStyle::WaterPlant => if (tick / 2) & 1 == 0 { PET_WATER_A } else { PET_WATER_B },
            CritterStyle::Fume => if (tick / 4) & 1 == 0 { PET_SULK_A } else { PET_SULK_B },
            CritterStyle::KickGround => if tick & 1 == 0 { PET_SULK_A } else { PET_KICK },
        }
    };
    draw_frame(sugarloaf, display, scale, x, y, draw_facing, frame, ink);

    if resting {
        let (zx, zy) = (x - 1.0, y - 12.0);
        lcd_rect(sugarloaf, display, scale, [zx, zy, 4.0, 1.0], ink, ORDER_PET);
        lcd_rect(sugarloaf, display, scale, [zx + 2.0, zy + 1.0, 1.0, 1.0], ink, ORDER_PET);
        lcd_rect(sugarloaf, display, scale, [zx + 1.0, zy + 2.0, 1.0, 1.0], ink, ORDER_PET);
        lcd_rect(sugarloaf, display, scale, [zx, zy + 3.0, 4.0, 1.0], ink, ORDER_PET);
        if (tick / 4) & 1 == 1 {
            lcd_rect(sugarloaf, display, scale, [zx + 5.0, zy - 7.0, 3.0, 1.0], ink, ORDER_PET);
            lcd_rect(sugarloaf, display, scale, [zx + 6.0, zy - 6.0, 1.0, 1.0], ink, ORDER_PET);
            lcd_rect(sugarloaf, display, scale, [zx + 5.0, zy - 5.0, 3.0, 1.0], ink, ORDER_PET);
        }
    }
    if !pet.grabbed && !airborne && impact_seconds <= 0.0 {
        match moment {
            Some(Moment::Hiccup) => {
                if tick & 1 == 0 {
                    lcd_rect(sugarloaf, display, scale, [x + 6.0, y - 27.0, 1.0, 3.0], ink, ORDER_PET);
                    lcd_rect(sugarloaf, display, scale, [x + 6.0, y - 23.0, 1.0, 1.0], ink, ORDER_PET);
                }
            }
            Some(Moment::Sneeze) if pet.moment_phase() >= 0.45 => {
                lcd_rect(sugarloaf, display, scale, [x + 10.0 * facing, y - 16.0, 1.0, 1.0], ink, ORDER_PET);
                lcd_rect(sugarloaf, display, scale, [x + 12.0 * facing, y - 14.0, 1.0, 1.0], ink, ORDER_PET);
                lcd_rect(sugarloaf, display, scale, [x + 10.0 * facing, y - 12.0, 1.0, 1.0], ink, ORDER_PET);
            }
            Some(Moment::Dizzy) => {
                let (ox, oy) = [(-7.0, -24.0), (0.0, -27.0), (7.0, -24.0)][(tick % 3) as usize];
                lcd_rect(sugarloaf, display, scale, [x + ox, y + oy - 1.0, 1.0, 3.0], ink, ORDER_PET);
                lcd_rect(sugarloaf, display, scale, [x + ox - 1.0, y + oy, 3.0, 1.0], ink, ORDER_PET);
            }
            Some(_) => {}
            None => match style {
                CritterStyle::Dance | CritterStyle::AirGuitar | CritterStyle::Robot => {
                    let (nx, ny) = if (tick / 2) & 1 == 0 { (x + 10.0, y - 26.0) } else { (x - 14.0, y - 23.0) };
                    lcd_rect(sugarloaf, display, scale, [nx, ny + 3.0, 2.0, 2.0], ink, ORDER_PET);
                    lcd_rect(sugarloaf, display, scale, [nx + 2.0, ny, 1.0, 4.0], ink, ORDER_PET);
                    lcd_rect(sugarloaf, display, scale, [nx + 3.0, ny, 1.0, 2.0], ink, ORDER_PET);
                }
                CritterStyle::Juggle => {
                    let balls: [[f32; 2]; 3] = if tick & 1 == 0 {
                        [[-4.0, -26.0], [1.0, -30.0], [6.0, -26.0]]
                    } else {
                        [[-5.0, -29.0], [1.0, -24.0], [5.0, -30.0]]
                    };
                    for [bx, by] in balls {
                        lcd_rect(sugarloaf, display, scale, [x + bx, y + by, 2.0, 2.0], ink, ORDER_PET);
                    }
                }
                CritterStyle::Zoomies => {
                    let bx = if pet.facing_right { x - 14.0 } else { x + 11.0 };
                    lcd_rect(sugarloaf, display, scale, [bx, y - 16.0, 3.0, 1.0], ink, ORDER_PET);
                    lcd_rect(sugarloaf, display, scale, [bx + 2.0 * facing, y - 10.0, 3.0, 1.0], ink, ORDER_PET);
                }
                CritterStyle::Boxing if tick % 4 >= 2 => {
                    lcd_rect(sugarloaf, display, scale, [x - 7.0 * facing, y - 21.0, 1.0, 2.0], ink, ORDER_PET);
                }
                CritterStyle::Pushups | CritterStyle::Squats | CritterStyle::JumpRope
                    if (tick / 2) & 1 == 1 =>
                {
                    lcd_rect(sugarloaf, display, scale, [x - 8.0 * facing, y - 18.0, 1.0, 2.0], ink, ORDER_PET);
                }
                CritterStyle::Hammer if tick & 1 == 0 => {
                    lcd_rect(sugarloaf, display, scale, [x + 8.0 * facing, y - 15.0, 1.0, 1.0], ink, ORDER_PET);
                    lcd_rect(sugarloaf, display, scale, [x + 7.0 * facing, y - 10.0, 1.0, 1.0], ink, ORDER_PET);
                }
                CritterStyle::WaterPlant => {
                    lcd_rect(sugarloaf, display, scale, [x + 6.0 * facing, y - 5.0, 1.0, 1.0], ink, ORDER_PET);
                    if tick & 1 == 0 {
                        lcd_rect(sugarloaf, display, scale, [x + 7.0 * facing, y - 3.0, 1.0, 1.0], ink, ORDER_PET);
                    }
                }
                CritterStyle::BirdWatch => {
                    let span = WORLD_WIDTH + 40.0;
                    let bx = ((tick * 3) as f32 % span) - 20.0;
                    let by = 26.0 + ((tick / 2) & 1) as f32;
                    if tick & 1 == 0 {
                        lcd_rect(sugarloaf, display, scale, [bx, by, 2.0, 1.0], ink, ORDER_PET);
                        lcd_rect(sugarloaf, display, scale, [bx + 3.0, by, 2.0, 1.0], ink, ORDER_PET);
                        lcd_rect(sugarloaf, display, scale, [bx + 2.0, by + 1.0, 1.0, 1.0], ink, ORDER_PET);
                    } else {
                        lcd_rect(sugarloaf, display, scale, [bx, by + 1.0, 2.0, 1.0], ink, ORDER_PET);
                        lcd_rect(sugarloaf, display, scale, [bx + 3.0, by + 1.0, 2.0, 1.0], ink, ORDER_PET);
                        lcd_rect(sugarloaf, display, scale, [bx + 2.0, by, 1.0, 1.0], ink, ORDER_PET);
                    }
                }
                _ => {}
            },
        }
    }
    if pet.red_cheeks() {
        let (cx, top) = if pet.grabbed || airborne {
            (x, y - 21.0)
        } else if impact_seconds > 0.0 {
            (x, y - 11.0)
        } else if resting {
            (x - 5.0, y - 5.0)
        } else if matches!(style, CritterStyle::Fume | CritterStyle::KickGround) {
            (x, y - 19.0)
        } else {
            (x, y - 20.0)
        };
        lcd_rect(sugarloaf, display, scale, [cx - 4.0, top - 4.0, 1.0, 3.0], anger, ORDER_PET);
        lcd_rect(sugarloaf, display, scale, [cx, top - 5.0, 1.0, 4.0], anger, ORDER_PET);
        lcd_rect(sugarloaf, display, scale, [cx + 4.0, top - 4.0, 1.0, 3.0], anger, ORDER_PET);
    }
}

fn draw_frame(
    sugarloaf: &mut Sugarloaf,
    display: [f32; 4],
    scale: f32,
    x: f32,
    y: f32,
    facing_right: bool,
    rows: &[&str],
    color: [f32; 4],
) {
    let height = rows.len() as f32;
    for (r, row) in rows.iter().enumerate() {
        let oy = y + r as f32 - (height - 1.0);
        let bytes = row.as_bytes();
        let width = bytes.len();
        let mut run_start: Option<usize> = None;
        for c in 0..=width {
            let ink = c < width && bytes[c] == b'#';
            match (ink, run_start) {
                (true, None) => run_start = Some(c),
                (false, Some(start)) => {
                    let col = if facing_right { start } else { width - c };
                    lcd_rect(
                        sugarloaf,
                        display,
                        scale,
                        [x + col as f32 - 8.0, oy, (c - start) as f32, 1.0],
                        color,
                        ORDER_PET,
                    );
                    run_start = None;
                }
                _ => {}
            }
        }
    }
}
