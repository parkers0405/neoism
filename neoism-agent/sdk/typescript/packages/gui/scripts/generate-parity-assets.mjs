#!/usr/bin/env node
// No dependencies. Run from any cwd; never downloads data or scans user themes.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = new URL('../../../../../../', import.meta.url);
const output = new URL('../src/generated/', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const match = (text, regex, label) => {
  const m = text.match(regex);
  assert(m, `Native source format changed: ${label}`);
  return m;
};
const ide = read('neoism-frontend/shared/src/primitives/ide_theme.rs');
const nv = read('neoism-frontend/shared/src/primitives/nvchad_themes.rs');
const nativeCommands = read('neoism-frontend/shared/src/panels/agent_pane/command_controller.rs');
const avatar = read('neoism-frontend/shared/src/editor/crdt/presence_avatar.rs');
const svg = read('neoism-frontend/web/public/favicon.svg');
const license = read('THIRD_PARTY_LICENSES/NvChad-base46.txt');
const header = '// @generated by scripts/generate-parity-assets.mjs; do not edit.\n';
const sha = text => createHash('sha256').update(text).digest('hex');
const fields = [...match(ide, /pub struct IdeTheme \{([\s\S]*?)\n\}/, 'palette struct')[1]
  .matchAll(/pub (\w+): u32/g)].map(m => m[1]);
assert.equal(fields.length, 27);
const colors = entries => {
  const c = Object.fromEntries(entries);
  assert.deepEqual(Object.keys(c), fields, 'Every Rust palette field must be extracted in order');
  for (const value of Object.values(c)) assert.match(value, /^#[0-9a-f]{6}$/);
  return { ...c, background: c.bg, foreground: c.fg };
};
const displayName = id => id.replace(/([a-z])([A-Z])/g, '$1 $2').split(/[_ -]/)
  .map(word => word[0].toUpperCase() + word.slice(1)).join(' ');
const builtinIds = [...match(ide, /pub fn as_str\(self\)[\s\S]*?\n    \}/, 'theme IDs')[0]
  .matchAll(/IdeThemeName::(\w+) => "([^"]+)"/g)].map(m => m[2]);
assert.equal(builtinIds.length, 4);
const themes = builtinIds.map(id => {
  const body = match(ide, new RegExp(`pub fn ${id}\\(\\) -> Self \\{\\s*Self \\{([\\s\\S]*?)\\n        \\}`), id)[1];
  return { id, name: displayName(id), colors: colors([...body.matchAll(/(\w+): 0x([0-9a-fA-F]{6}),/g)]
    .map(m => [m[1], '#' + m[2].toLowerCase()])) };
});
const mapping = [...match(ide, /Some\(IdeTheme \{([\s\S]*?)\n    \}\)/, 'packed palette mapping')[1]
  .matchAll(/(\w+): c\[(\d+)\]/g)].map(m => [m[1], Number(m[2])]);
const packedThemes = [...nv.matchAll(/\("([^"]+)", "([0-9a-f]+)"\)/g)];
assert.equal(packedThemes.length, 97);
for (const [, id, packed] of packedThemes) {
  assert.equal(packed.length, 26 * 6, id);
  themes.push({ id, name: displayName(id), colors: colors(mapping.map(([key, index]) =>
    [key, '#' + packed.slice(index * 6, index * 6 + 6)])) });
}
assert.equal(themes.length, 101);
assert.equal(new Set(themes.map(t => t.id)).size, themes.length);

const planner = match(nativeCommands, /pub fn plan_slash_command[\s\S]*?\n\}/, 'command planner')[0];
const groups = [...planner.matchAll(/^\s*((?:"\/[^"\n]+"\s*\|\s*)*"\/[^"\n]+")\s*=>/gm)]
  .map(m => [...m[1].matchAll(/"([^"]+)"/g)].map(n => n[1]));
const specs = match(nativeCommands, /fn slash_option_specs\(\)[\s\S]*?\n\}/, 'picker catalog')[0];
const commands = [...specs.matchAll(/SlashOptionSpec \{([\s\S]*?)\}/g)].map(([, body]) => {
  const name = match(body, /title:\s*"([^"]+)"/, 'command title')[1];
  const description = JSON.parse(match(body, /description:\s*("(?:[^"\\]|\\.)*")/, 'command description')[1]);
  const group = groups.filter(g => g.includes(name));
  assert.equal(group.length, 1, `No unique alias group for ${name}`);
  return { name, description, aliases: group[0].filter(alias => alias !== name) };
});
assert.equal(commands.length, 32);
const spellings = commands.flatMap(c => [c.name, ...c.aliases]);
assert.equal(new Set(spellings).size, spellings.length);
assert.deepEqual([...spellings].sort(), groups.flat().sort(), 'All native aliases must be represented');
assert(commands.find(c => c.name === '/model').aliases.includes('/models'));

const path = match(svg, /<path d="([^"]+)"/, 'favicon N path')[1];
assert.equal([...svg.matchAll(/<path\b/g)].length, 1);
// Preserve the original path, with its own tight bounds instead of the icon tile transform.
assert.match(path, /^[MLZ\d.\s-]+$/);
const points = [...path.matchAll(/[ML]\s*(-?[\d.]+)\s+(-?[\d.]+)/g)].map(m => [+m[1], +m[2]]);
const xs = points.map(p => p[0]), ys = points.map(p => p[1]);
const viewBox = [Math.min(...xs), Math.min(...ys), Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)].join(' ');
const revision = match(nv, /BASE46_REVISION: &str = "([^"]+)"/, 'Base46 revision')[1];
const files = new Map([
  ['themes.ts', header + `/*!\n${license.trim()}\nBundled Base46 revision: ${revision}\n*/\n` +
    'export type Theme = { id: string; name: string; colors: Record<string, string> };\n' +
    `export const themes: Theme[] = ${JSON.stringify(themes, null, 2)};\n`],
  ['commands.ts', header + 'export type SlashCommand = { name: string; description: string; aliases: string[] };\n' +
    `export const commands: SlashCommand[] = ${JSON.stringify(commands, null, 2)};\n`],
  ['logo.ts', header + '// Exact favicon letterform; no background rects or squircle.\n' +
    `export const neoismLogoPath = ${JSON.stringify(path)};\nexport const neoismLogoViewBox = ${JSON.stringify(viewBox)};\n`],
  ['avatar.ts', header + `// Native source SHA-256: ${sha(avatar)}\n` +
    readFileSync(new URL('avatar.template.ts', import.meta.url), 'utf8')],
  ['NvChad-base46.LICENSE.txt', license],
]);
const check = process.argv.includes('--check');
assert(process.argv.slice(2).every(arg => arg === '--check'), 'Usage: generate-parity-assets.mjs [--check]');
if (!check) mkdirSync(output, { recursive: true });
let drift = false;
for (const [name, content] of files) {
  const url = new URL(name, output);
  if (check) {
    let current;
    try { current = readFileSync(url, 'utf8'); } catch { /* Missing file is drift. */ }
    if (current !== content) { console.error(`Parity asset drift: ${fileURLToPath(url)}`); drift = true; }
  } else writeFileSync(url, content);
}
if (drift) process.exitCode = 1;
else console.log(`${check ? 'Checked' : 'Generated'} 101 themes, 32 commands (${spellings.length} spellings), logo, avatar, and license.`);
