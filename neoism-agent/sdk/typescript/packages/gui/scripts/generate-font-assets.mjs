#!/usr/bin/env node
// Offline, dependency-free copies of curated fonts already committed in Neoism.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';

const root = new URL('../../../../../../', import.meta.url);
const gui = new URL('../', import.meta.url);
const browser = 'neoism-frontend/web/public/fonts/';
const illuminated = 'neoism-frontend/shared/assets/illuminated/fonts/google-ofl/';
const styles = [['Regular', 400, 'normal'], ['Bold', 700, 'normal'], ['Italic', 400, 'italic'], ['BoldItalic', 700, 'italic']];
export const fontSources = [
  { id: 'geist-mono', name: 'Geist Mono', kind: 'monospace', fallback: 'ui-monospace, monospace',
    description: 'Neoism browser monospace; regular, bold, italic and bold italic.',
    license: 'GeistMono-OFL.txt', upstream: 'https://github.com/vercel/geist-font/tree/1.5.0',
    faces: styles.map(([suffix, weight, style]) => ({ source: `${browser}geist-mono/GeistMono-${suffix}.otf`, weight, style })) },
  { id: 'jetbrains-mono', name: 'JetBrains Mono', kind: 'monospace', fallback: 'ui-monospace, monospace',
    description: 'Neoism browser coding font; regular, bold, italic and bold italic.',
    license: 'JetBrainsMono-OFL.txt', upstream: 'https://github.com/JetBrains/JetBrainsMono/tree/v2.304',
    faces: styles.map(([suffix, weight, style]) => ({ source: `${browser}jetbrains-mono/JetBrainsMono-${suffix}.woff2`, weight, style })) },
  { id: 'cinzel-decorative', name: 'Cinzel Decorative', kind: 'display', fallback: 'serif',
    description: 'Proportional display serif from native illuminated markdown; best for headings, not code.',
    license: 'CinzelDecorative-OFL.txt', upstream: 'https://github.com/google/fonts/tree/main/ofl/cinzeldecorative',
    faces: ['Regular', 'Bold'].map((suffix, i) => ({ source: `${illuminated}CinzelDecorative-${suffix}.ttf`, weight: i ? 700 : 400, style: 'normal' })) },
  { id: 'medieval-sharp', name: 'MedievalSharp', kind: 'display', fallback: 'serif',
    description: 'Proportional display font from native illuminated markdown; regular face only.',
    license: 'MedievalSharp-OFL.txt', upstream: 'https://github.com/google/fonts/tree/main/ofl/medievalsharp',
    faces: [{ source: `${illuminated}MedievalSharp.ttf`, weight: 400, style: 'normal' }] },
  { id: 'geist', name: 'Geist', family: 'Geist', cssFamily: 'Geist, ui-sans-serif, system-ui, sans-serif', kind: 'sans-serif', fallback: 'ui-sans-serif, system-ui, sans-serif',
    description: 'Proportional variable UI sans-serif; continuous weights 100–900.',
    license: 'Geist-OFL.txt', upstream: 'https://github.com/vercel/geist-font/tree/10dc7658f13c38a474cde201bb09a4617267545b',
    faces: [{ source: 'neoism-agent/sdk/typescript/packages/gui/scripts/assets/geist/Geist-Variable.ttf', weight: '100 900', style: 'normal' }] },
  { id: 'press-start-2p', name: 'Press Start 2P', family: 'Press Start 2P', kind: 'display', fallback: 'monospace',
    description: 'Exact native agent side-panel pixel heading face; regular 400, scalable, approximately 12px for compact headings.',
    license: 'PressStart2P-OFL.txt', upstream: 'https://github.com/google/fonts/tree/main/ofl/pressstart2p',
    faces: [{ source: 'sugarloaf/src/font/resources/PressStart2P/PressStart2P-Regular.ttf', weight: 400, style: 'normal' }] },
];
const formats = {
  otf: { format: 'opentype', mime: 'font/otf', signature: '4f54544f' },
  ttf: { format: 'truetype', mime: 'font/ttf', signature: '00010000' },
  woff2: { format: 'woff2', mime: 'font/woff2', signature: '774f4632' },
};
const hash = bytes => createHash('sha256').update(bytes).digest('hex');

export function buildFontAssets() {
  const files = new Map(), fonts = [], provenance = [];
  let css = '/* @generated by scripts/generate-font-assets.mjs; do not edit. */\n';
  css += '/*! Fonts are SIL OFL-1.1; preserve public/fonts/licenses when distributing. */\n';
  for (const font of fontSources) {
    const family = font.family ?? `Neoism ${font.name}`;
    const faces = font.faces.map(face => {
      const filename = face.source.split('/').at(-1);
      const { format, mime, signature } = formats[filename.split('.').at(-1)];
      const bytes = readFileSync(new URL(face.source, root));
      assert.equal(bytes.subarray(0, 4).toString('hex'), signature, `Invalid font: ${face.source}`);
      const destination = `public/fonts/${font.id}/${filename}`;
      const url = `/fonts/${font.id}/${filename}`;
      files.set(destination, bytes);
      provenance.push({ source: face.source, destination, bytes: bytes.length, sha256: hash(bytes), mime });
      css += `\n@font-face {\n  font-family: ${JSON.stringify(family)};\n  src: url(${JSON.stringify(url)}) format(${JSON.stringify(format)});\n  font-weight: ${face.weight};\n  font-style: ${face.style};\n  font-display: swap;\n}\n`;
      return { url, weight: face.weight, style: face.style, format };
    });
    const licenseSource = `neoism-agent/sdk/typescript/packages/gui/scripts/font-licenses/${font.license}`;
    const license = readFileSync(new URL(licenseSource, root));
    assert.match(license.toString(), /SIL OPEN FONT LICENSE Version 1.1/);
    const licenseDestination = `public/fonts/licenses/${font.license}`;
    files.set(licenseDestination, license);
    provenance.push({ source: licenseSource, destination: licenseDestination, bytes: license.length, sha256: hash(license), mime: 'text/plain' });
    fonts.push({ id: font.id, name: font.name, family, cssFamily: font.cssFamily ?? `${JSON.stringify(family)}, ${font.fallback}`,
      kind: font.kind, availability: 'bundled', description: font.description,
      licenseUrl: `/fonts/licenses/${font.license}`, faces });
  }
  const systemFontOptions = [
    { id: 'system-sans', name: 'Default sans', family: 'Geist', cssFamily: 'Geist, ui-sans-serif, system-ui, sans-serif', kind: 'sans-serif' },
    { id: 'system-serif', name: 'System serif', family: 'serif', cssFamily: 'serif', kind: 'serif' },
    { id: 'system-mono', name: 'System monospace', family: 'monospace', cssFamily: 'ui-monospace, monospace', kind: 'monospace' },
  ].map(font => ({ ...font, availability: 'system-fallback', description: font.id === 'system-sans' ? 'Bundled Geist with browser/OS sans-serif fallbacks.' : 'Browser/OS-selected family; exact font varies by device.', faces: [] }));
  const localFontAccess = {
    api: 'queryLocalFonts', requiresSecureContext: true, requiresUserPermission: true,
    availability: 'runtime-only',
    description: 'Optional Local Font Access API; feature-detect window.queryLocalFonts and request from a user gesture. Never assume desktop-installed fonts exist in this browser.',
    fallback: 'Allow an explicit user-entered CSS family with a generic fallback; label it unverified. No local fonts are enumerated by this catalog.',
  };
  const ts = `// @generated by scripts/generate-font-assets.mjs; do not edit.
export type FontFaceAsset = {
  url: string; weight: number | \`\${number} \${number}\`; style: 'normal' | 'italic'; format: 'opentype' | 'truetype' | 'woff2';
};
export type FontOption = {
  id: string; name: string; family: string; cssFamily: string;
  kind: 'monospace' | 'sans-serif' | 'serif' | 'display';
  availability: 'bundled' | 'system-fallback'; description: string;
  faces: FontFaceAsset[]; licenseUrl?: string;
};
/** Only fonts whose files ship with this GUI. Import ./fonts.css once to register them. */
export const fonts: FontOption[] = ${JSON.stringify(fonts, null, 2)};
/** Generic fallbacks, NOT claims about named installed fonts. */
export const systemFontOptions: FontOption[] = ${JSON.stringify(systemFontOptions, null, 2)};
/** Capability guidance, NOT a discovered list or a request for permission. */
export const localFontAccess = ${JSON.stringify(localFontAccess, null, 2)} as const;
`;
  files.set('src/generated/fonts.ts', Buffer.from(ts));
  files.set('src/generated/fonts.css', Buffer.from(css));
  files.set('public/fonts/SOURCES.json', Buffer.from(JSON.stringify({
    generator: 'scripts/generate-font-assets.mjs', license: 'OFL-1.1',
    note: 'Unmodified source copies. Upstream URLs identify projects/license sources; source hashes identify the exact bundled bytes.',
    families: fontSources.map(({ id, upstream, license }) => ({ id, upstream, license })), files: provenance,
  }, null, 2) + '\n'));
  return files;
}

export function generateFontAssets(check = false) {
  const files = buildFontAssets();
  let drift = false;
  for (const [path, bytes] of files) {
    const url = new URL(path, gui);
    if (check) {
      let current;
      try { current = readFileSync(url); } catch { /* Missing output is drift. */ }
      if (!current?.equals(bytes)) { console.error(`Font asset drift: ${path}`); drift = true; }
    } else {
      mkdirSync(new URL('.', url), { recursive: true });
      writeFileSync(url, bytes);
    }
  }
  if (drift) return false;
  console.log(`${check ? 'Checked' : 'Generated'} ${fontSources.length} bundled font families, ${fontSources.flatMap(font => font.faces).length} font faces, ${fontSources.length} OFL notices, CSS and metadata.`);
  return true;
}
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  assert(process.argv.slice(2).every(arg => arg === '--check'), 'Usage: generate-font-assets.mjs [--check]');
  if (!generateFontAssets(process.argv.includes('--check'))) process.exitCode = 1;
}
